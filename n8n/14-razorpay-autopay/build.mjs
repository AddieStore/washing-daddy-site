// Builds 14-razorpay-autopay.json. Run: node n8n/14-razorpay-autopay/build.mjs
// Same shape as workflow 13: every endpoint is Webhook -> Code -> Respond, and one shared Telegram line for Ravi.
// Each Code node embeds n8n/13-pronto/lib.js (token check, Firestore, Razorpay helpers) and then ./sub.js.
// Edit sub.js (or 13's lib.js), then run this, then node test.mjs.
import fs from 'node:fs';
const lib13 = fs.readFileSync(new URL('../13-pronto/lib.js', import.meta.url), 'utf8');
const sub = fs.readFileSync(new URL('./sub.js', import.meta.url), 'utf8');

const ENDPOINTS = [
  ['wd-sub-create', 'Autopay shuru karo'],
  ['wd-sub-confirm', 'Autopay pakka karo'],
  ['wd-sub-hook', 'Autopay webhook (Razorpay)'],
  ['wd-sub-cancel', 'Autopay band karo'],
];
const RAW = ['wd-sub-hook'];   // Razorpay signs the exact bytes it sent

const code = name => `// Workflow 14, endpoint ${name}. Logic: n8n/13-pronto/lib.js + n8n/14-razorpay-autopay/sub.js (generated by build.mjs: edit those, not this node).
// Secrets come from n8n env vars only: FIREBASE_PROJECT_ID, FIREBASE_SA_KEY_B64, RAZORPAY_KEY_ID, RAZORPAY_KEY_SECRET, RAZORPAY_WEBHOOK_SECRET.
// Needs NODE_FUNCTION_ALLOW_BUILTIN=crypto and N8N_BLOCK_ENV_ACCESS_IN_NODE=false (already set for workflows 9 and 13).
const crypto = require('crypto');
${lib13}
${sub}
const self = this;
const http = async o => {
  const opts = { method: o.method, url: o.url, headers: Object.assign({}, o.headers || {}), returnFullResponse: true, ignoreHttpStatusErrors: true, timeout: 20000, json: true };
  if (o.form) {
    opts.body = Object.keys(o.form).map(k => encodeURIComponent(k) + '=' + encodeURIComponent(o.form[k])).join('&');
    opts.headers['Content-Type'] = 'application/x-www-form-urlencoded';
  } else if (o.body !== undefined) opts.body = o.body;
  const r = await self.helpers.httpRequest(opts);
  let body = r.body; if (typeof body === 'string') { try { body = JSON.parse(body); } catch (e) {} }
  return { statusCode: r.statusCode, body, headers: r.headers || {} };
};
const inp = $input.first();
let rawBody = '';
${RAW.includes(name) ? `// the signature is over the exact bytes Razorpay sent, so read the raw body
try { rawBody = (await this.helpers.getBinaryDataBuffer(0, 'data')).toString('utf8'); } catch (e) {
  if (inp.binary && inp.binary.data && inp.binary.data.data) rawBody = Buffer.from(inp.binary.data.data, 'base64').toString('utf8');
  else if (typeof inp.json.rawBody === 'string') rawBody = inp.json.rawBody;
}` : ''}
const req = { headers: inp.json.headers || {}, body: inp.json.body || {}, rawBody };
const ctx = { env: $env, http, sd: $getWorkflowStaticData('global'), crypto, now: Date.now() };
const r = await handleSub(${JSON.stringify(name)}, ctx, req);
return [{ json: { status: r.status, body: r.body, notify: r.notify || '', alert: r.alert || '' } }];`;

const nodes = [], connections = {};
const link = (from, ...to) => { connections[from] = { main: [to.map(n => ({ node: n, type: 'main', index: 0 }))] }; };
ENDPOINTS.forEach(([path, label], i) => {
  const y = i * 220, wh = label + ' (webhook)', cn = label, rn = label + ' jawab';
  nodes.push({ parameters: { path, httpMethod: 'POST', responseMode: 'responseNode', options: RAW.includes(path) ? { rawBody: true } : {} },
    id: path + '-webhook', name: wh, type: 'n8n-nodes-base.webhook', typeVersion: 2, position: [0, y], webhookId: path });
  nodes.push({ parameters: { jsCode: code(path) }, id: path + '-code', name: cn, type: 'n8n-nodes-base.code', typeVersion: 2, position: [240, y] });
  nodes.push({ parameters: { respondWith: 'json', responseBody: '={{ JSON.stringify($json.body) }}', options: { responseCode: '={{ $json.status }}' } },
    id: path + '-respond', name: rn, type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1, position: [480, y] });
  link(wh, cn);
  link(cn, rn, 'Ravi ko batana hai? (14)');
});
nodes.push({ parameters: { conditions: { options: { caseSensitive: true, leftValue: '', typeValidation: 'loose' }, combinator: 'and',
  conditions: [{ id: 'c', operator: { type: 'boolean', operation: 'true', singleValue: true }, leftValue: '={{ !!($json.notify || $json.alert) }}', rightValue: '' }] }, options: {} },
  id: 'tell-ravi-if-14', name: 'Ravi ko batana hai? (14)', type: 'n8n-nodes-base.if', typeVersion: 2, position: [720, 0] });
nodes.push({ parameters: { chatId: '={{ $env.TELEGRAM_CHAT_ID || "" }}', text: '={{ ($json.alert ? "⚠ " + $json.alert + "\\n" : "") + ($json.notify || "") }}', additionalFields: {} },
  id: 'tell-ravi-14', name: 'Ravi ko batao (14)', type: 'n8n-nodes-base.telegram', typeVersion: 1.2, position: [960, 0],
  credentials: { telegramApi: { id: 'REPLACE_ME', name: 'Telegram account' } }, continueOnFail: true, onError: 'continueRegularOutput' });
link('Ravi ko batana hai? (14)', 'Ravi ko batao (14)'); connections['Ravi ko batana hai? (14)'].main.push([]);

fs.writeFileSync(new URL('./14-razorpay-autopay.json', import.meta.url),
  JSON.stringify({ name: '14 — Razorpay autopay (monthly plans)', nodes, connections, settings: { executionOrder: 'v1' }, pinData: {} }, null, 2));
console.log('built 14-razorpay-autopay.json:', nodes.length, 'nodes');
