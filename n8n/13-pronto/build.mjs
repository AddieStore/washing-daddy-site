// Builds 13-pronto.json from lib.js. Run: node n8n/13-pronto/build.mjs
// Every endpoint is Webhook -> Code (lib.js handle()) -> Respond. All Code nodes share one Telegram line for Ravi
// and one call to workflow 10 (wd-ondemand-dispatch) for paid instant bookings.
import fs from 'node:fs';
const lib = fs.readFileSync(new URL('./lib.js', import.meta.url), 'utf8');

const ENDPOINTS = [
  ['wd-booking-create', 'Booking banao'],
  ['wd-booking-cancel', 'Booking cancel karo'],
  ['wd-booking-reschedule', 'Booking aage-peeche karo'],
  ['wd-coupon-validate', 'Coupon jaancho'],
  ['wd-wallet-topup', 'WD Money top-up'],
  ['wd-gift-claim', 'Gift card lagao'],
  ['wd-pass-buy', 'WD Pass becho'],
  ['wd-pronto-paid', 'Paisa aaya (from workflow 8)'],
  ['wd-rzp-confirm', 'Razorpay paisa pakka karo'],
  ['wd-rzp-hook', 'Razorpay webhook'],
];
const RAW = ['wd-pronto-paid', 'wd-rzp-hook'];   // signature is over the exact bytes sent

const code = name => `// Workflow 13, endpoint ${name}. Logic: n8n/13-pronto/lib.js (generated by build.mjs: edit lib.js, not this node).
// Secrets come from n8n env vars only (README: CASHFREE_APP_ID, CASHFREE_SECRET, FIREBASE_PROJECT_ID, FIREBASE_SA_KEY_B64, RAZORPAY_KEY_ID, RAZORPAY_KEY_SECRET, RAZORPAY_WEBHOOK_SECRET).
// Needs NODE_FUNCTION_ALLOW_BUILTIN=crypto and N8N_BLOCK_ENV_ACCESS_IN_NODE=false (both already set for workflow 9).
const crypto = require('crypto');
${lib}
const self = this;
const http = async o => {
  const opts = { method: o.method, url: o.url, headers: Object.assign({}, o.headers || {}), returnFullResponse: true, ignoreHttpStatusErrors: true, timeout: 20000, json: true };
  if (o.form) {
    opts.body = Object.keys(o.form).map(k => encodeURIComponent(k) + '=' + encodeURIComponent(o.form[k])).join('&');
    opts.headers['Content-Type'] = 'application/x-www-form-urlencoded';
  } else if (o.body !== undefined) opts.body = o.body;
  const r = await self.helpers.httpRequest(opts);
  let body = r.body; if (typeof body === 'string') { try { body = JSON.parse(body); } catch (e) {} }
  return { statusCode: r.statusCode, body, headers: r.headers || {} };
};
const inp = $input.first();
let rawBody = '';
${RAW.includes(name) ? `// the signature is over the exact bytes Cashfree sent, so read the raw body
try { rawBody = (await this.helpers.getBinaryDataBuffer(0, 'data')).toString('utf8'); } catch (e) {
  if (inp.binary && inp.binary.data && inp.binary.data.data) rawBody = Buffer.from(inp.binary.data.data, 'base64').toString('utf8');
  else if (typeof inp.json.rawBody === 'string') rawBody = inp.json.rawBody;
}` : ''}
const req = { headers: inp.json.headers || {}, body: inp.json.body || {}, rawBody };
const ctx = { env: $env, http, sd: $getWorkflowStaticData('global'), crypto, now: Date.now() };
const r = await handle(${JSON.stringify(name)}, ctx, req);
return [{ json: { status: r.status, body: r.body, notify: r.notify || '', alert: r.alert || '', dispatch: r.dispatch || '' } }];`;

const nodes = [], connections = {};
const ifNode = (name, id, expr, pos) => ({ parameters: { conditions: { options: { caseSensitive: true, leftValue: '', typeValidation: 'loose' }, combinator: 'and',
  conditions: [{ id: 'c', operator: { type: 'boolean', operation: 'true', singleValue: true }, leftValue: expr, rightValue: '' }] }, options: {} },
  id, name, type: 'n8n-nodes-base.if', typeVersion: 2, position: pos });
const link = (from, ...to) => { connections[from] = { main: [to.map(n => ({ node: n, type: 'main', index: 0 }))] }; };

ENDPOINTS.forEach(([path, label], i) => {
  const y = i * 220, wh = label + ' (webhook)', cn = label, rn = label + ' jawab';
  nodes.push({ parameters: { path, httpMethod: 'POST', responseMode: 'responseNode', options: RAW.includes(path) ? { rawBody: true } : {} },
    id: path + '-webhook', name: wh, type: 'n8n-nodes-base.webhook', typeVersion: 2, position: [0, y], webhookId: path });
  nodes.push({ parameters: { jsCode: code(path) }, id: path + '-code', name: cn, type: 'n8n-nodes-base.code', typeVersion: 2, position: [240, y] });
  nodes.push({ parameters: { respondWith: 'json', responseBody: '={{ JSON.stringify($json.body) }}', options: { responseCode: '={{ $json.status }}' } },
    id: path + '-respond', name: rn, type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1, position: [480, y] });
  link(wh, cn);
  link(cn, rn, 'Ravi ko batana hai?', 'Dispatch karna hai?');
});
nodes.push(ifNode('Ravi ko batana hai?', 'tell-ravi-if', '={{ !!($json.notify || $json.alert) }}', [720, 0]));
nodes.push({ parameters: { chatId: '={{ $env.TELEGRAM_CHAT_ID || "" }}', text: '={{ ($json.alert ? "⚠ " + $json.alert + "\\n" : "") + ($json.notify || "") }}', additionalFields: {} },
  id: 'tell-ravi', name: 'Ravi ko batao (13)', type: 'n8n-nodes-base.telegram', typeVersion: 1.2, position: [960, 0],
  credentials: { telegramApi: { id: 'REPLACE_ME', name: 'Telegram account' } }, continueOnFail: true, onError: 'continueRegularOutput' });
nodes.push(ifNode('Dispatch karna hai?', 'dispatch-if', '={{ !!$json.dispatch }}', [720, 220]));
nodes.push({ parameters: { method: 'POST', url: '={{ ($env.WD_N8N_INTERNAL || "http://localhost:5678") + "/webhook/wd-ondemand-dispatch" }}',
    sendBody: true, specifyBody: 'json', jsonBody: '={{ JSON.stringify({ doc_id: $json.dispatch }) }}', options: { response: { response: { neverError: true } }, timeout: 15000 } },
  id: 'dispatch-call', name: 'Washer bhejo (workflow 10)', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position: [960, 220], continueOnFail: true, onError: 'continueRegularOutput' });
link('Ravi ko batana hai?', 'Ravi ko batao (13)'); connections['Ravi ko batana hai?'].main.push([]);
link('Dispatch karna hai?', 'Washer bhejo (workflow 10)'); connections['Dispatch karna hai?'].main.push([]);

fs.writeFileSync(new URL('./13-pronto.json', import.meta.url),
  JSON.stringify({ name: '13 — Pronto money (bookings, WD Money, WD Pass)', nodes, connections, settings: { executionOrder: 'v1' }, pinData: {} }, null, 2));
console.log('built 13-pronto.json:', nodes.length, 'nodes');
