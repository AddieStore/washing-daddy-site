// Builds src/assets/car3dHtml.ts, the self-contained "Car Studio" page loaded in a WebView / iframe.
// Source of truth: the 3D preview page (three.js r160 + Web Audio engine + base64 clips + smoke overlay).
//   node scripts/build-car3d.mjs [path/to/car3d-preview.html] [path/to/three.min.js]
// If three.min.js is not given it is fetched from jsdelivr (three@0.160.0) at build time, so the output has no CDN link.
// Embed mode: the host sets window.WD = { plate, car, embed:true, sab?, sat? } before the page runs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcPath = process.argv[2] || '/mnt/project-files/preview/car3d-preview.html';
const threeArg = process.argv[3];
const out = path.join(here, '..', 'src', 'assets', 'car3dHtml.ts');

let html = fs.readFileSync(srcPath, 'utf8');
const three = threeArg ? fs.readFileSync(threeArg, 'utf8')
  : await (await fetch('https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.min.js')).text();
if (!/REVISION="160"|REVISION = "160"|"160"/.test(three.slice(0, 4000)) && !three.includes('160')) throw new Error('unexpected three.js build');
const safe = three.replace(/<\/script/gi, '<\\/script');

const must = (s, what) => { if (!html.includes(s)) throw new Error('source page changed, missing: ' + what); };
const CDN = '<script src="https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.min.js"></script>';
must(CDN, 'three CDN tag');
html = html.replace(CDN, () => '<script>' + safe + '</script>');

// plate text from the host
must("fillText('DL4CAB2731',590,168,800)", 'plate text');
html = html.replace("fillText('DL4CAB2731',590,168,800)", "fillText(String((window.WD&&WD.plate)||'DL4CAB2731').toUpperCase().replace(/[^A-Z0-9]/g,'').slice(0,10)||'DL4CAB2731',590,168,800)");

// pick the starting car (before the first frame)
must('requestAnimationFrame(loop);\nsetTimeout(function(){ var h=$(\'hint\')', 'main loop start');
html = html.replace('requestAnimationFrame(loop);\nsetTimeout(function(){ var h=$(\'hint\')',
  "try{ if(window.WD&&WD.car&&WD.car!=='hatch') setCar(WD.car); }catch(e){}\nrequestAnimationFrame(loop);\nsetTimeout(function(){ var h=$('hint')");

// in embed mode the engine switches itself off a few seconds after the rev button is let go
must('function releaseRev(){\n  if(!S.held) return; S.held=false; revBtn.classList.remove(\'down\'); Aud.revStop();',
  'releaseRev');
html = html.replace("function releaseRev(){\n  if(!S.held) return; S.held=false; revBtn.classList.remove('down'); Aud.revStop();",
  "function releaseRev(){\n  if(!S.held) return; S.held=false; revBtn.classList.remove('down'); Aud.revStop();\n  if(window.WD&&WD.embed) setTimeout(function(){ if(!S.held&&S.engine) setEngine(false); },4500);");

// embed mode: only the car, picker, exhaust chips, rev button and smoke
const EMBED_HEAD = `<script>window.WD=window.WD||{};if(WD.embed){document.documentElement.className+=' embed';
var r=document.documentElement.style;if(WD.sab!=null)r.setProperty('--sab',WD.sab+'px');r.setProperty('--sat',(WD.sat||0)+'px');}</script>
<style>
html.embed header,html.embed h1,html.embed .sub,html.embed .hint,html.embed .gauge,html.embed .tag,html.embed .colors,html.embed .engine,html.embed .note,html.embed .rev small{display:none!important}
html.embed .app{padding-top:calc(var(--sat) + 8px)}
html.embed .stage{min-height:0}
html.embed .controls{margin-top:12px}
</style>
</head>`;
must('</head>', 'head');
html = html.replace('</head>', () => EMBED_HEAD);

const body = 'export const CAR3D_HTML: string = ' + JSON.stringify(html) + ';\n';
fs.writeFileSync(out, '// Generated by scripts/build-car3d.mjs. Do not edit by hand.\n' + body);
console.log('wrote', out, (fs.statSync(out).size / 1e6).toFixed(2) + ' MB');
