const CURVE = Easing.bezier(0.22, 1, 0.36, 1);
function useReduceMotion() {
  const [rm, setRm] = useState(false);
  useEffect(() => { AccessibilityInfo.isReduceMotionEnabled().then(setRm, () => {}); }, []);
  return rm;
}

const MoneyTab = () => <Money tab />;
const SCREEN: Record<Tab, () => React.ReactElement> = { home: Home, live: Live, plan: Plan, store: Store, profile: Profile, money: MoneyTab };

// Every page id in state.ts `Page` (openPage({ k, ...params })) -> its screen. CORE-owned: workers do not edit this file.
// The switch is exhaustive, so adding a kind to `Page` without a screen here fails tsc.
function PageView({ p }: { p: NonNullable<Page> }): React.ReactElement {
  switch (p.k) {
    case 'svc': return <Service id={p.id} />;
    case 'cart': return <Cart />;
    case 'schedule': return <Schedule />;
    case 'money': return <Money />;
    case 'refunds': return <Refunds />;
    case 'pass': return <Pass id={p.id} />;
    case 'coupons': return <Coupons />;
    case 'refer': return <Refer />;
    case 'profile': return <Profile />;
    case 'profileEdit': return <ProfileEdit />;
    case 'addresses': return <Addresses pick={p.pick} />;
    case 'addressMap': return <AddressMap id={p.id} />;
    case 'addressForm': return <AddressForm id={p.id} lat={p.lat} lng={p.lng} area={p.area} />;
    case 'help': return <Help />;
    case 'helpTopic': return <HelpTopic id={p.id} />;
    case 'legal': return <Legal />;
    case 'legalDoc': return <LegalDoc id={p.id} />;
    case 'deleteAccount': return <DeleteAccount />;
    case 'about': return <About />;
    case 'bookings': return <Bookings />;
    case 'booking': return <Booking id={p.id} />;
    case 'rate': return <Rate id={p.id} />;
    case 'txn': return <Txn id={p.id} />;
    case 'supportIssues': return <SupportIssues bookingId={p.bookingId} title={p.title} />;
    case 'supportChat': return <SupportChat id={p.id} />;
    case 'orders': return <Orders />;
    case 'washer': return <Washer id={p.id} name={p.name} />;
    case 'payResult': return <PayResult />;
    case 'parkAlerts': return <ParkAlerts />;
    default: { const never: never = p; return never }
  }
}

const CUR = REasing.bezier(0.22, 1, 0.36, 1);
const enterOf = (k: string) => k === 'svc' ? FadeIn.duration(200) : k === 'cart' ? SlideInDown.duration(380).easing(CUR) : SlideInRight.duration(320).easing(CUR);
const exitOf = (k: string) => k === 'svc' ? FadeOut.duration(180) : k === 'cart' ? SlideOutDown.duration(260).easing(CUR) : SlideOutRight.duration(240).easing(CUR);
type Cover = null | 'slide' | 'zoom';
const coverOf = (k?: string): Cover => !k ? null : k === 'svc' || k === 'cart' ? 'zoom' : 'slide';

/** recede when something is pushed on top; spring back when it goes */
function useCover(cover: Cover) {
  const { width } = useWindowDimensions(), rm = useReducedMotion(), v = useSharedValue(0), mode = useSharedValue(1);
  useEffect(() => { if (cover) mode.value = cover === 'slide' ? 1 : 2; v.value = rm ? (cover ? 1 : 0) : cover ? withTiming(1, { duration: 320, easing: CUR }) : withSpring(0, { damping: 24, stiffness: 220, overshootClamping: true }) }, [cover, rm]);
  const st = useAnimatedStyle(() => mode.value === 1
    ? { transform: [{ translateX: -width * 0.28 * v.value }] }
    : { transform: [{ scale: 1 - 0.06 * v.value }], borderRadius: 18 * v.value, overflow: 'hidden' as const });
  const dim = useAnimatedStyle(() => ({ opacity: 0.28 * v.value }));
  return { st, dim };
}

/** one soft violet tint at the top of every page that fades into the canvas, so all screens share the same background */
function PageFade({ day = true }: { day?: boolean }) {
  if (!day) return null;
  return <LinearGradient pointerEvents="none" colors={['rgba(84,9,218,0.13)', 'rgba(84,9,218,0.05)', 'rgba(84,9,218,0)']} locations={[0, 0.45, 1]} style={{ position: 'absolute', left: 0, right: 0, top: 0, height: 340 }} />;
}

function Pushed({ p, depth, cover }: { p: NonNullable<Page>; depth: number; cover: Cover }) {
  const rm = useReduceMotion(), c = useCover(cover);
  return (
    <Reanimated.View entering={rm ? undefined : enterOf(p.k)} exiting={rm ? undefined : exitOf(p.k)} style={{ position: 'absolute', left: 0, right: 0, top: 0, bottom: 0, zIndex: 10 + depth, backgroundColor: '#000' }}>
      <Reanimated.View style={[{ flex: 1, backgroundColor: '#FFFFFF' }, c.st]}>
        <PageFade />
        <PageView p={p} />
      </Reanimated.View>
      <Reanimated.View pointerEvents="none" style={[StyleSheet.absoluteFill, { backgroundColor: '#0B0614' }, c.dim]} />
    </Reanimated.View>
  );
}

/** a tab the live config switched off falls back to Home */
const tabAllowed = (t: Tab) => t === 'home' || (t === 'live' ? tabOn('washes') : t === 'money' ? tabOn('money') : t === 'profile' ? tabOn('profile') : t === 'store' ? feature('store') : t === 'plan' ? feature('plans') : true);
/** appcfg maintenance.on: a full-screen notice instead of the app (WhatsApp still works) */
function Maintenance({ message }: { message: string }) {
  return (
    <View style={{ flex: 1, backgroundColor: '#fff', alignItems: 'center', justifyContent: 'center', padding: 32 }}>
      <GenericArt size={180} icon="clock" accent="#5409DA" />
      <Txt weight={600} size={20} style={{ marginTop: 16, textAlign: 'center' }}>Back shortly</Txt>
      <Txt size={14} color="#525252" style={{ marginTop: 8, textAlign: 'center', lineHeight: 20 }}>{message}</Txt>
      <Txt weight={600} size={14} color="#5409DA" style={{ marginTop: 20 }} onPress={() => act.whatsapp('Hi Washing Daddy')}>Chat with us</Txt>
    </View>
  );
}

export default function Main() {
  const ui = useApp(), T = useTheme(), rm = useReduceMotion(), fade = useRef(new Animated.Value(1)).current, tab: Tab = tabAllowed(ui.tab) ? ui.tab : 'home', Screen = SCREEN[tab];
  useEffect(() => {
    if (rm) return;
    fade.setValue(0);
    Animated.timing(fade, { toValue: 1, duration: 200, easing: CURVE, useNativeDriver: true }).start();
  }, [ui.tab, rm]);
  useEffect(() => {
    const s = BackHandler.addEventListener('hardwareBackPress', () => { if (ui.pages.length) { closePage(); return true } return false });
    return () => s.remove();
  }, [ui.pages.length]);
  const [primer, setPrimer] = useState(false);
  useEffect(() => { needsPrimer().then(v => { primerGate.on = v; setPrimer(v) }) }, []);
  const key = tab === 'home' || tab === 'live' ? tab : tab + ':' + ui.tabNonce;
  // Keep Home and Washes mounted once visited: re-mounting the heavy Home screen on every tap of its tab was the lag.
  // Hidden ones use display:none (no layout, no paint, state and scroll position kept). Other tabs mount fresh as before.
  const kept = useRef<Set<Tab>>(new Set()); if (tab === 'home' || tab === 'live') kept.current.add(tab);
  const tabCover = useCover(coverOf(ui.pages[0]?.k)), mt = appCfg().maintenance;
  if (mt.on) return <Maintenance message={mt.message} />;
  return (
    <View style={{ flex: 1, backgroundColor: '#000' }}>
      <Reanimated.View style={[{ flex: 1, backgroundColor: T.bg }, tabCover.st]}>
        <PageFade day={T.day} />
        {(['home', 'live'] as Tab[]).filter(k => kept.current.has(k)).map(k => { const S2 = SCREEN[k], on = k === tab;
          return <Animated.View key={k} style={on ? { flex: 1, opacity: fade } : { display: 'none' }}><S2 /></Animated.View> })}
        {tab !== 'home' && tab !== 'live' ? <Animated.View key={key} style={{ flex: 1, opacity: fade }}><Screen /></Animated.View> : null}
        <TabBar />
        <StatusBar style={tab === 'home' && !ui.pages.length ? 'dark' : 'light'} />
      </Reanimated.View>
      <Reanimated.View pointerEvents="none" style={[StyleSheet.absoluteFill, { backgroundColor: '#0B0614' }, tabCover.dim]} />
      {ui.pages.map((p, i) => p && <Pushed key={i + ':' + p.k + ('id' in p && p.id ? p.id : '')} p={p} depth={i} cover={coverOf(ui.pages[i + 1]?.k)} />)}
      <FlyHost />
      {primer ? <Permissions onDone={() => { primerGate.on = false; setPrimer(false) }} /> : null}
    </View>
  );
}
