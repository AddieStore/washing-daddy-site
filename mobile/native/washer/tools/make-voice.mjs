// Generates the Hindi "Extra kaam aaya hai ... rupaye" voice clips with ElevenLabs.
// Run once (clips are then committed), from mobile/native/washer:
//   ELEVENLABS_API_KEY=... ELEVENLABS_VOICE_ID=... node --experimental-strip-types tools/make-voice.mjs
// Put the key in the environment, never on the command line or in git. Optional: --only intro,n7,sau  (redo some clips)
// Writes assets/sound/voice/<key>.mp3 and src/lib/voiceClips.ts (so Metro bundles them).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { HINDI_WORDS } from '../src/lib/hindiNumber.ts';

const key = process.env.ELEVENLABS_API_KEY, voice = process.env.ELEVENLABS_VOICE_ID;
if (!key || !voice) { console.error('Set ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID in the environment.'); process.exit(2); }
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'assets/sound/voice'); fs.mkdirSync(dir, { recursive: true });
const onlyArg = process.argv.indexOf('--only'); const only = onlyArg > 0 ? process.argv[onlyArg + 1].split(',') : null;

for (const [k, text] of Object.entries(HINDI_WORDS)) {
  const file = path.join(dir, k + '.mp3');
  if (only ? !only.includes(k) : fs.existsSync(file)) continue;
  const r = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voice}?output_format=mp3_44100_64`, {
    method: 'POST', headers: { 'xi-api-key': key, 'content-type': 'application/json' },
    body: JSON.stringify({ text, model_id: 'eleven_multilingual_v2', language_code: 'hi', voice_settings: { stability: 0.6, similarity_boost: 0.8 } }),
  });
  if (!r.ok) { console.error(k, r.status, (await r.text()).slice(0, 200)); process.exit(1); }
  fs.writeFileSync(file, Buffer.from(await r.arrayBuffer()));
  console.log('ok', k, text);
}
const have = fs.readdirSync(dir).filter(f => f.endsWith('.mp3')).map(f => f.slice(0, -4)).sort();
fs.writeFileSync(path.join(root, 'src/lib/voiceClips.ts'),
  '// Generated by tools/make-voice.mjs: maps clip key -> bundled mp3.\nexport const VOICE_CLIPS: Record<string, number> = {\n'
  + have.map(k => `  ${k}: require('../../assets/sound/voice/${k}.mp3'),`).join('\n') + '\n};\n');
console.log(have.length, 'clips ready');
