export function hiOf(t: string): string | null {
  const s = t.trim();
  if (!s) return null;
  const hit = HI[s];
  if (hit) return t.replace(s, hit);
  for (const [re, out] of HI_PATTERNS) if (re.test(s)) return t.replace(s, s.replace(re, out));
  if (s.includes(' · ')) {
    let any = false;
    const done = s.split(' · ').map(part => {
      const h = HI[part];
      if (h) { any = true; return h }
      for (const [re, out] of HI_PATTERNS) if (re.test(part)) { any = true; return part.replace(re, out) }
      return part;
    });
    if (any) return t.replace(s, done.join(' · '));
  }
  return null;
}

